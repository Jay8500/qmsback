// Vaccination certificate PDF (SRS 2.x2): made on the server with pdfmake (already a dependency),
// with a QR code that opens the public verification page.
// Input: one row of fn_vaccination_certificate_get + the app's base URL (sent by the browser).
const PdfPrinter = require('pdfmake');
const vfsFonts = require('pdfmake/build/vfs_fonts');

const vfs = vfsFonts.pdfMake ? vfsFonts.pdfMake.vfs : (vfsFonts.vfs || vfsFonts);
const font = (name) => Buffer.from(vfs[name], 'base64');
const printer = new PdfPrinter({
    Roboto: {
        normal: font('Roboto-Regular.ttf'),
        bold: font('Roboto-Medium.ttf'),
        italics: font('Roboto-Italic.ttf'),
        bolditalics: font('Roboto-MediumItalic.ttf'),
    },
});

// Only an http(s) origin is accepted for the QR link; anything else falls back to a relative path.
function verifyLink(baseUrl, code) {
    const base = /^https?:\/\/[^\s]+$/i.test(String(baseUrl || '')) ? String(baseUrl).replace(/\/+$/, '') : '';
    return `${base}/verify-certificate/${code}`;
}

const text = (value) => (value === null || value === undefined || value === '' ? '-' : String(value));

function buildDocument(cert, baseUrl) {
    const link = verifyLink(baseUrl, cert.verify_code);
    const doses = Array.isArray(cert.doses) ? cert.doses : [];
    return {
        pageSize: 'A4',
        pageMargins: [40, 40, 40, 50],
        defaultStyle: { font: 'Roboto', fontSize: 10, color: '#222222' },
        content: [
            { text: text(cert.org_name), style: 'org' },
            { text: text(cert.location_name), alignment: 'center', color: '#666666', margin: [0, 0, 0, 12] },
            { text: 'VACCINATION CERTIFICATE', style: 'title' },
            {
                columns: [
                    {
                        width: '*',
                        table: {
                            widths: [120, '*'],
                            body: [
                                ['Certificate No.', { text: text(cert.certificate_no), bold: true }],
                                ['Employee', text(cert.employee_name)],
                                ['Employee ID', text(cert.employee_code)],
                                ['Department', text(cert.department_name)],
                                ['Vaccine', { text: text(cert.vaccine_name), bold: true }],
                                ['Manufacturer', text(cert.manufacturer_name)],
                                ['Doses completed', `${text(cert.doses_completed)} of ${text(cert.doses_total)}`],
                                ['Issued', `${text(cert.issued_at)} by ${text(cert.issued_by)}`],
                                ['Policy', cert.policy_version ? `Adheres to ${cert.policy_version}` : '-'],
                            ],
                        },
                        layout: 'noBorders',
                    },
                    {
                        width: 130,
                        stack: [
                            { qr: link, fit: 120, alignment: 'center' },
                            { text: 'Scan to verify', alignment: 'center', fontSize: 8, color: '#666666', margin: [0, 4, 0, 0] },
                        ],
                    },
                ],
                margin: [0, 8, 0, 14],
            },
            { text: 'Doses', style: 'section' },
            {
                table: {
                    headerRows: 1,
                    widths: [45, 70, '*', 70, '*', '*'],
                    body: [
                        ['Dose', 'Date', 'Brand', 'Batch', 'Vaccinated By', 'Venue'].map((h) => ({ text: h, bold: true, fillColor: '#eef3f8' })),
                        ...doses.map((d) => [text(d.dose_label), text(d.administered_at), text(d.brand_name), text(d.batch_no), text(d.vaccinated_by), text(d.venue_name)]),
                    ],
                },
                layout: 'lightHorizontalLines',
            },
            { text: `Verify at: ${link}`, fontSize: 8, color: '#666666', margin: [0, 16, 0, 0] },
            { text: 'This certificate is generated by the Hospital Quality Management System. It is valid only while the QR verification shows "Valid".', fontSize: 8, color: '#666666', margin: [0, 4, 0, 0] },
        ],
        styles: {
            org: { fontSize: 16, bold: true, alignment: 'center', color: '#1a5c2e' },
            title: { fontSize: 14, bold: true, alignment: 'center', margin: [0, 4, 0, 10], color: '#1d4f91' },
            section: { fontSize: 11, bold: true, margin: [0, 4, 0, 6] },
        },
    };
}

// Returns the PDF as a Buffer.
function buildPdf(cert, baseUrl) {
    return new Promise((resolve, reject) => {
        try {
            const doc = printer.createPdfKitDocument(buildDocument(cert, baseUrl));
            const chunks = [];
            doc.on('data', (chunk) => chunks.push(chunk));
            doc.on('end', () => resolve(Buffer.concat(chunks)));
            doc.on('error', reject);
            doc.end();
        } catch (err) {
            reject(err);
        }
    });
}

module.exports = { buildPdf };
